/** One backup the Lab puts into the (Lab) backup folder: [daysAgo] days before the Lab day at [hour]:[minute]; daysAgo 0 is "now" (after the data was seeded). */
data class LabBackup(val daysAgo: Int, val hour: Int, val minute: Int, val type: SnapshotType)

/**
 * What loading a scenario puts into the (Lab) database: the settings, the series with FIXED ids (rows below point at them), the
 * rows that are not generated by a series, the series that ask for the amount each time and the backups to create. Series rows from a
 * rule's start date on that are not listed here are generated by the normal maintenance afterwards, exactly as in the real app.
 */
data class LabSeed(
    val settings: AppSettings,
    val rules: List<RecurringRule> = emptyList(),
    val transactions: List<Transaction> = emptyList(),
    val askAmountRuleIds: Set<Long> = emptySet(),
    val backups: List<LabBackup> = emptyList(),
)

/**
 * One screen of a check: where the Lab takes the person by itself ([target], given the scenario's day), what it moves the clock by first
 * ([clockShiftDays], the Lab's time machine), and 2 to 4 yes/no questions to answer by looking. Nothing here asks anyone to type,
 * create, edit or delete.
 */
class LabStep(
    val checks: List<String>,
    val clockShiftDays: Int = 0,
    val target: (today: LocalDate) -> UiTarget,
)

/**
 * One test scenario of the Lab build: an id, a title, one line, its steps (each a screen to look at with its questions), the clock to apply
 * (null keeps real time) and a PURE seed builder. [seed] gets the day that is "today" in the scenario.
 */
class LabScenario(
    val id: String,
    val title: String,
    val description: String,
    val steps: List<LabStep>,
    val clock: LocalDateTime?,
    val seed: (today: LocalDate) -> LabSeed,
) {
    /** Every question of the scenario, in order. */
    val checks: List<String> get() = steps.flatMap { it.checks }

    /** The day the scenario runs on: its clock day, or the real day when it keeps real time. */
    fun today(realToday: LocalDate): LocalDate = clock?.toLocalDate() ?: realToday

    fun build(realToday: LocalDate): LabSeed = seed(today(realToday))

    /** The screens of the scenario for [today]. */
    fun targets(today: LocalDate): List<UiTarget> = steps.map { it.target(today) }
}

/**
 * The catalogue. Every release adds or updates scenarios for exactly what it changes (see docs/RELEASE_RULES.md): a scenario never asks
 * the person to type, create, edit or delete anything; it seeds its data, navigates itself and asks 2 to 4 yes/no questions per screen.
 * Pure data: no Android classes, so the seeds are unit tested on the JVM.
 */
object LabScenarios {
    /** The day most scenarios run on: a Monday, 12 October 2026. */
    val BASE_DAY: LocalDate = LocalDate.of(2026, 10, 12)
    private val NINE = LocalTime.of(9, 0)
    private fun at(day: LocalDate) = LocalDateTime.of(day, NINE)

    private const val M = 1000L

    private fun one(date: LocalDate, tnd: Long, name: String, kind: TxKind = TxKind.EXPENSE, status: TxStatus = TxStatus.PENDING) = Transaction(
        date = date, amount = tnd * M, kind = kind, description = name, status = status, source = TxSource.MANUAL, isPlanned = true,
    )

    /** An expense entered as "Now": accepted at once, not planned. */
    private fun now(date: LocalDate, tnd: Long, name: String) = Transaction(
        date = date, amount = tnd * M, kind = TxKind.EXPENSE, description = name, status = TxStatus.CONFIRMED, source = TxSource.MANUAL, isPlanned = false,
    )

    private fun series(
        id: Long, name: String, tnd: Long, kind: TxKind, pattern: RecurrencePattern, start: LocalDate, end: LocalDate? = null,
    ) = RecurringRule(id = id, amount = tnd * M, kind = kind, description = name, pattern = pattern, startDate = start, endDate = end, confirmTime = LocalTime.NOON)

    /** A row of series [rule] that was already answered (it keeps its date and amount). */
    private fun answered(rule: RecurringRule, date: LocalDate, status: TxStatus = TxStatus.CONFIRMED) =
        rule.occurrenceFor(date).copy(status = status)

    private fun settings(balanceTnd: Long, from: LocalDate) = AppSettings(startingBalance = balanceTnd * M, balanceStartDate = from, reminderTime = LocalTime.NOON)

    private fun step(vararg checks: String, shiftDays: Int = 0, target: (LocalDate) -> UiTarget) = LabStep(checks.toList(), shiftDays, target)

